// UploadInfo is an uploaded draft attachment (plan 5.6).
type UploadInfo struct {
	ID          string  `json:"id" example:"u_91"`
	Filename    string  `json:"filename" example:"umowa.pdf"`
	Size        int64   `json:"size" example:"1203311"`
	ContentType string  `json:"contentType" example:"application/pdf"`
	Inline      bool    `json:"inline" doc:"A picture shown in the body as cid:<cid> (pasted into the editor); it is sent in multipart/related. An inline upload the body does not refer to is sent as a plain attachment."`
	CID         *string `json:"cid" nullable:"true" example:"5f0c1e2d9a8b4c7d6e5f4a3b2c1d0e9f@silo" doc:"Content-ID of an inline upload, generated by the server (without <>): put it in the HTML as <img src=\"cid:<cid>\">. null for other uploads."`
	Thumbnail   bool    `json:"thumbnail" doc:"GET /attachments/{id}/thumbnail serves a thumbnail (png, jpeg, gif, webp)."`
}

func uploadOf(u drafts.Upload) UploadInfo {
	out := UploadInfo{ID: formatID("u_", u.ID), Filename: u.Filename, Size: u.Size, ContentType: u.ContentType,
		Inline: u.Inline, Thumbnail: mailview.ThumbnailSupported(u.ContentType)}
	if u.CID != "" {
		cid := u.CID
		out.CID = &cid
	}
	return out
}

// uploadInput takes the raw request: the multipart body is streamed by the
// handler, never buffered by huma.
type uploadInput struct {
	contentType string
	length      int64 // Content-Length, -1 when not sent
	body        io.Reader
	inline      bool // ?inline=true
}

// Resolve captures the request body and its content type.
func (i *uploadInput) Resolve(ctx huma.Context) []error {
	i.contentType, i.body = ctx.Header("Content-Type"), ctx.BodyReader()
	i.inline = truthy(ctx.Query("inline"))
	// net/http moves Content-Length out of the header map.
	r, _ := humachi.Unwrap(ctx)
	i.length = r.ContentLength
	return nil
}

func truthy(s string) bool {
	switch strings.ToLower(strings.TrimSpace(s)) {
	case "true", "1", "yes", "on":
		return true
	}
	return false
}

type uploadOutput struct {
	Status int
	Body   UploadInfo
}

// uploadFile streams the first file part of a multipart/form-data body. A
// field inline=true before the file part (or ?inline=true) makes it an
// inline picture.
func (d *deps) uploadFile(ctx context.Context, userID int64, ct string, length int64, body io.Reader, inline bool) (*drafts.Upload, error) {
	mt, params, err := mime.ParseMediaType(ct)
	if err != nil || mt != "multipart/form-data" || params["boundary"] == "" {
		return nil, problem(http.StatusBadRequest, CodeValidation, "Expected a multipart/form-data body with one file.")
	}
	// The form may carry small fields before the file; bound the whole body.
	limit := d.drafts.MaxUploadBytes() + 1<<20
	mr := multipart.NewReader(http.MaxBytesReader(nil, io.NopCloser(body), limit), params["boundary"])
	for {
		part, err := mr.NextPart()
		var mbe *http.MaxBytesError
		switch {
		case errors.As(err, &mbe):
			return nil, errUploadTooLarge(d.drafts.MaxUploadBytes(), length)
		case errors.Is(err, io.EOF):
			return nil, problem(http.StatusBadRequest, CodeValidation, "The form has no file part.")
		case err != nil:
			return nil, problem(http.StatusBadRequest, CodeValidation, "Cannot read the multipart body.")
		}
		if part.FileName() == "" {
			if part.FormName() == "inline" {
				v, _ := io.ReadAll(io.LimitReader(part, 16))
				inline = inline || truthy(string(v))
			}
			_ = part.Close()
			continue
		}
		u, err := d.drafts.Upload(ctx, userID, part.FileName(), part.Header.Get("Content-Type"), inline, part)
		_ = part.Close()
		if errors.Is(err, drafts.ErrTooLarge) || errors.As(err, &mbe) {
			return nil, errUploadTooLarge(d.drafts.MaxUploadBytes(), length)
		}
		if errors.Is(err, drafts.ErrInlineNotImage) {
			return nil, problem(http.StatusUnprocessableEntity, CodeInlineNotImage, "Only an image (image/*) can be an inline upload.")
		}
		if err != nil {
			return nil, errInternal(err)
		}
		return u, nil
	}
}

func errUploadTooLarge(limit, size int64) error {
	p := problem(http.StatusRequestEntityTooLarge, CodeUploadTooLarge,
		"The file is larger than the attachment limit of "+formatBytes(limit)+".")
	p.Limit = &limit
	if size >= 0 {
		p.Size = &size
	}
	return p
}

func formatBytes(n int64) string {
	switch {
	case n >= 1<<20 && n%(1<<20) == 0:
		return strconv.FormatInt(n>>20, 10) + " MB"
	case n >= 1<<10 && n%(1<<10) == 0:
		return strconv.FormatInt(n>>10, 10) + " KB"
	}
	return strconv.FormatInt(n, 10) + " bytes"
}

